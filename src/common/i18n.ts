export function t(
  locale: string | undefined,
  key: string,
  params: Record<string, string> = {},
): string {
  const loc = (locale as Locale) || 'ua';
  let text = translations[loc]?.[key] || translations.ua[key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replaceAll(`{${k}}`, v);
  }
  return text;
}
